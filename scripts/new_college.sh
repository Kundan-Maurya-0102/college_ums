#!/usr/bin/env bash
# Scaffold a new college deployment: creates a per-college .env with fresh
# secrets and prints the exact commands to start it. Secrets are written to
# disk only (chmod 600) and never echoed to the terminal.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

usage() {
    cat <<'EOF'
Usage: scripts/new_college.sh --name "College Name" --domain ums.college.edu [options]

Required:
  --name NAME      College display name (used in templates and messages)
  --domain DOMAIN  Public hostname, e.g. ums.college.edu

Optional:
  --slug SLUG      Deployment + database identifier (default: derived from name)
  --email EMAIL    Public contact email shown on the website page
  --phone PHONE    Public contact phone
  --color HEX      Brand colour (default: #000080)
  --logo PATH      Static logo path (images/logo.png) or https URL
  --address TEXT   Public postal address
  --affiliation X  Affiliation line, e.g. "SBTE Bihar"
  --established Y  Year of establishment, e.g. 2016
  --out DIR        Output root (default: <repo>/deployments)
  -h, --help       Show this help
EOF
}

name="" domain="" slug="" email="" phone="" color="#000080" logo="images/college_logo.jpg"
address="" affiliation="" established="" out="$ROOT_DIR/deployments"

while [ $# -gt 0 ]; do
    case "$1" in
        --name) name="${2:-}"; shift 2 ;;
        --domain) domain="${2:-}"; shift 2 ;;
        --slug) slug="${2:-}"; shift 2 ;;
        --email) email="${2:-}"; shift 2 ;;
        --phone) phone="${2:-}"; shift 2 ;;
        --color) color="${2:-}"; shift 2 ;;
        --logo) logo="${2:-}"; shift 2 ;;
        --address) address="${2:-}"; shift 2 ;;
        --affiliation) affiliation="${2:-}"; shift 2 ;;
        --established) established="${2:-}"; shift 2 ;;
        --out) out="${2:-}"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "ERROR: unknown option '$1'" >&2; usage; exit 2 ;;
    esac
done

[ -n "$name" ] || { echo "ERROR: --name is required" >&2; usage; exit 2; }
[ -n "$domain" ] || { echo "ERROR: --domain is required" >&2; usage; exit 2; }

if ! printf '%s' "$domain" | grep -Eq '^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$'; then
    echo "ERROR: invalid domain '$domain' (use a bare hostname, no scheme or path)" >&2
    exit 2
fi

if [ -z "$slug" ]; then
    slug="$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/_/g; s/^_+//; s/_+$//')"
fi
if ! printf '%s' "$slug" | grep -Eq '^[a-z][a-z0-9_]{1,30}$'; then
    echo "ERROR: invalid slug '$slug' (lowercase letters, digits, underscore; 2-31 chars)" >&2
    exit 2
fi

deploy_dir="$out/$slug"
if [ -e "$deploy_dir" ]; then
    echo "ERROR: '$deploy_dir' already exists; choose another --slug or remove it" >&2
    exit 1
fi

mkdir -p "$deploy_dir"
chmod 700 "$deploy_dir"

if command -v python3 >/dev/null 2>&1; then
    secret_key="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
else
    secret_key="$(openssl rand -base64 64 | tr -d '\n')"
fi
db_password="$(openssl rand -hex 24)"
db_name="$slug"
db_user="$slug"
env_file="$deploy_dir/.env"

umask 077
cat > "$env_file" <<EOF
# Generated by scripts/new_college.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — keep private.
SECRET_KEY=$secret_key
ENVIRONMENT=production
DEBUG=False
COLLEGE_SLUG=$slug
COLLEGE_DOMAIN=$domain
ALLOWED_HOSTS=$domain,www.$domain,localhost,127.0.0.1
CSRF_TRUSTED_ORIGINS=https://$domain,https://www.$domain
PORTAL_URL=https://$domain
DOMAIN=$domain
ENV_FILE=$env_file

DB_ENGINE=django.db.backends.postgresql
DB_NAME=$db_name
DB_USER=$db_user
DB_PASSWORD=$db_password
DB_HOST=db
DB_PORT=5432

COLLEGE_NAME=$name
COLLEGE_LOGO=$logo
PRIMARY_COLOR=$color
COLLEGE_EMAIL=$email
COLLEGE_PHONE=$phone
COLLEGE_ADDRESS=$address
COLLEGE_WEBSITE=https://$domain
COLLEGE_AFFILIATION=$affiliation
COLLEGE_ESTABLISHED=$established
COLLEGE_PRINCIPAL_NAME=

CSV_MAX_UPLOAD_MB=5
PASSWORD_TOKEN_TIMEOUT_HOURS=48
GUNICORN_WORKERS=3
GUNICORN_TIMEOUT=60
LOG_LEVEL=INFO
LOG_FORMAT=json
Q_WORKERS=2
DATA_RETENTION_YEARS=7
BACKUP_RETENTION_DAYS=14
# Report usage to the platform owner (optional)
PLATFORM_URL=
PLATFORM_METRICS_TOKEN=
# Error tracking (optional)
SENTRY_DSN=
SENTRY_ENV=production
EOF
chmod 600 "$env_file"
umask 022

compose_cmd="docker compose -p $slug -f docker-compose.prod.yml --env-file $env_file"

cat > "$deploy_dir/README.md" <<EOF
# Deployment: $name

Domain: \`$domain\` · Database: \`$db_name\` · Slug/project: \`$slug\`

Secrets live in \`.env\` in this folder (chmod 600). Never commit it.

## Start / update
\`\`\`bash
cd $ROOT_DIR
$compose_cmd up -d --build
\`\`\`

## First admin account
\`\`\`bash
$compose_cmd exec web python manage.py createsuperuser
\`\`\`

## Logs
\`\`\`bash
$compose_cmd logs -f web caddy
\`\`\`

## Database backup / restore
\`\`\`bash
$compose_cmd exec db pg_dump -U $db_user $db_name > backup-$(date +%Y%m%d).sql
cat backup.sql | $compose_cmd exec -T db psql -U $db_user $db_name
\`\`\`

## Stop (keeps data)
\`\`\`bash
$compose_cmd down
\`\`\`
EOF

cat <<EOF
Created deployment '$slug' at $deploy_dir
  env:    $env_file (chmod 600)
  domain: $domain

Next steps:
  1. Point DNS A/AAAA records for $domain to this server (ports 80 and 443 open).
  2. Start the stack:
       cd $ROOT_DIR
       $compose_cmd up -d --build
  3. Create the admin account:
       $compose_cmd exec web python manage.py createsuperuser
  4. Open https://$domain/login/

Other colleges: run this script again with a new --name/--domain. Each gets its
own database, volumes and project name.
EOF
